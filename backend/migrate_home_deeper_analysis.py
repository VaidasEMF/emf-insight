
from sqlalchemy import inspect, text

from db.database import engine


def migrate_home_deeper_analysis():

    if engine.dialect.name != "postgresql":
        raise RuntimeError("This migration requires PostgreSQL.")

    inspector = inspect(engine)

    required_tables = {
        "home_deeper_analyses",
        "properties",
        "property_health_records",
        "measurement_cycles",
        "projects",
    }

    missing_tables = {
        table
        for table in required_tables
        if not inspector.has_table(table)
    }

    if missing_tables:
        raise RuntimeError(
            "Migration prerequisites are missing. "
            f"Missing tables: {sorted(missing_tables)}. "
            "Run init_db() first."
        )

    with engine.begin() as connection:

        # ==========================================
        # HOME DEEPER ANALYSIS — PROPERTY / PHR / CYCLE
        # ==========================================

        connection.execute(text("""
            ALTER TABLE home_deeper_analyses
            ADD COLUMN IF NOT EXISTS property_id INTEGER
            REFERENCES properties(id)
        """))

        connection.execute(text("""
            ALTER TABLE home_deeper_analyses
            ADD COLUMN IF NOT EXISTS property_health_record_id INTEGER
            REFERENCES property_health_records(id)
        """))

        connection.execute(text("""
            ALTER TABLE home_deeper_analyses
            ADD COLUMN IF NOT EXISTS measurement_cycle_id INTEGER
            REFERENCES measurement_cycles(id)
        """))

        connection.execute(text("""
            CREATE INDEX IF NOT EXISTS ix_home_deeper_analyses_property_id
            ON home_deeper_analyses (property_id)
        """))

        connection.execute(text("""
            CREATE INDEX IF NOT EXISTS ix_home_deeper_analyses_property_health_record_id
            ON home_deeper_analyses (property_health_record_id)
        """))

        connection.execute(text("""
            CREATE INDEX IF NOT EXISTS ix_home_deeper_analyses_measurement_cycle_id
            ON home_deeper_analyses (measurement_cycle_id)
        """))

        # One Measurement Cycle can have only one Deeper Analysis.
        connection.execute(text("""
            CREATE UNIQUE INDEX IF NOT EXISTS
                uq_home_deeper_analyses_measurement_cycle_id
            ON home_deeper_analyses (measurement_cycle_id)
            WHERE measurement_cycle_id IS NOT NULL
        """))

        # ==========================================
        # REPEAT ANALYSIS — RESERVATIONS TABLE
        # ==========================================

        connection.execute(text("""
            CREATE TABLE IF NOT EXISTS home_deeper_repeat_reservations (

                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                measurement_cycle_id INTEGER NOT NULL
                    REFERENCES measurement_cycles(id)
                    ON DELETE RESTRICT,

                project_id INTEGER NOT NULL
                    REFERENCES projects(id)
                    ON DELETE RESTRICT,

                property_id INTEGER NOT NULL
                    REFERENCES properties(id)
                    ON DELETE RESTRICT,

                property_health_record_id INTEGER NOT NULL
                    REFERENCES property_health_records(id)
                    ON DELETE RESTRICT,

                user_id VARCHAR(255) NOT NULL,

                stripe_session_id VARCHAR(255) UNIQUE,

                status VARCHAR(20) NOT NULL DEFAULT 'pending'
                    CHECK (
                        status IN ('pending', 'completed', 'expired')
                    ),

                expires_at TIMESTAMPTZ NOT NULL,

                created_at TIMESTAMPTZ NOT NULL
                    DEFAULT CURRENT_TIMESTAMP,

                completed_at TIMESTAMPTZ
            )
        """))

        # One cycle can have only one active or completed reservation.
        connection.execute(text("""
            CREATE UNIQUE INDEX IF NOT EXISTS
                uq_home_deeper_repeat_cycle_reserved
            ON home_deeper_repeat_reservations (measurement_cycle_id)
            WHERE status IN ('pending', 'completed')
        """))

        connection.execute(text("""
            CREATE INDEX IF NOT EXISTS
                ix_home_deeper_repeat_reservations_project
            ON home_deeper_repeat_reservations (project_id)
        """))

        connection.execute(text("""
            CREATE INDEX IF NOT EXISTS
                ix_home_deeper_repeat_reservations_expiry
            ON home_deeper_repeat_reservations (expires_at)
            WHERE status = 'pending'
        """))

    # ==========================================
    # MIGRATION VERIFICATION
    # ==========================================

    inspector = inspect(engine)

    required_analysis_columns = {
        "property_id",
        "property_health_record_id",
        "measurement_cycle_id",
    }

    actual_analysis_columns = {
        column["name"]
        for column in inspector.get_columns("home_deeper_analyses")
    }

    missing_columns = (
        required_analysis_columns - actual_analysis_columns
    )

    if missing_columns:
        raise RuntimeError(
            f"Missing Home Deeper Analysis columns: {missing_columns}"
        )

    required_reservation_columns = {
        "id",
        "measurement_cycle_id",
        "project_id",
        "property_id",
        "property_health_record_id",
        "user_id",
        "stripe_session_id",
        "status",
        "expires_at",
        "created_at",
        "completed_at",
    }

    actual_reservation_columns = {
        column["name"]
        for column in inspector.get_columns(
            "home_deeper_repeat_reservations"
        )
    }

    missing_reservation_columns = (
        required_reservation_columns - actual_reservation_columns
    )

    if missing_reservation_columns:
        raise RuntimeError(
            "Missing Repeat Analysis reservation columns: "
            f"{missing_reservation_columns}"
        )

    required_indexes = {
        "uq_home_deeper_analyses_measurement_cycle_id",
        "uq_home_deeper_repeat_cycle_reserved",
        "ix_home_deeper_repeat_reservations_project",
        "ix_home_deeper_repeat_reservations_expiry",
    }

    actual_indexes = {
        index["name"]
        for table_name in (
            "home_deeper_analyses",
            "home_deeper_repeat_reservations",
        )
        for index in inspector.get_indexes(table_name)
    }

    missing_indexes = required_indexes - actual_indexes

    if missing_indexes:
        raise RuntimeError(
            f"Missing migration indexes: {missing_indexes}"
        )

    print("Home Deeper Analysis migration completed successfully.")
    print("Verified analysis columns:", sorted(required_analysis_columns))
    print("Verified reservation columns:", sorted(required_reservation_columns))
    print("Verified indexes:", sorted(required_indexes))


if __name__ == "__main__":
    migrate_home_deeper_analysis()
